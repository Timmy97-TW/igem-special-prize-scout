"""Build data/traditional.js: why GreatBay-SCIE and Lambert-GA sit outside the top 10.

Numbers come from field/teams.json (the three-judge panel). The prose lives in
field/traditional_prose.json, written after reading the ballots and checking the
decisive claims against the archived corpus.

usage (from the repo root): python3 field/scripts/build_traditional.py
"""
import json

T = {t['slug']: t for t in json.load(open('field/teams.json'))}
PROSE = json.load(open('field/traditional_prose.json'))
P = ['a1', 'a2', 'a3', 'a4', 'a5', 'a6', 'a7', 'a8']
W = ['w1', 'w2', 'w3', 'w4', 'w5']
WT = {**{k: .75 / 8 for k in P}, **{k: .25 / 5 for k in W}}
REFS = ['hongkong-jss', 'gems-taiwan', 'korea-hs']


def asp(sl):
    f = T[sl]['final']
    return {**f['project'], **f['wiki']}


def row(sl):
    t, f = T[sl], T[sl]['final']
    return {'slug': sl, 'team': t['team'], 'village': t['village'], 'country': t['country'], 'url': t['url'],
            'rank': f['rank'], 'combined': f['combined'], 'project_mean': f['project_mean'],
            'wiki_mean': f['wiki_mean'], 'aspects': asp(sl), 'judges': f['judges'],
            'screen': (t['screen'] or {}).get('screen_project'), 'ours': sl == 'gems-taiwan'}


ranked = sorted(((t['final']['combined'], t['team']) for t in T.values() if t['final']), reverse=True)


def place(score):
    return 1 + sum(1 for c, _ in ranked if c > score + 1e-9)


def what_if(sl, changes):
    a = asp(sl)
    return round(T[sl]['final']['combined'] + sum((v - a[k]) * WT[k] for k, v in changes.items()), 3)


teams = []
for sl, pr in PROSE['teams'].items():
    a, r = asp(sl), row(sl)
    r['gap'] = {ref: [{'k': k, 'd': round((a[k] - asp(ref)[k]) * WT[k], 3)} for k in P + W] for ref in REFS}
    r['judge_lines'] = [{'judge': j, 'one_line': T[sl]['deep'][j]['one_line']} for j in sorted(T[sl]['deep'])]
    r['what_if'] = []
    for w in pr.pop('what_if'):
        s = what_if(sl, w['set'])
        r['what_if'].append({'set': w['set'], 'score': s, 'place': place(s),
                             'en': w['en'].format(s=f'{s:.2f}', p=place(s)),
                             'zh': w['zh'].format(s=f'{s:.2f}', p=place(s))})
    r.update(pr)
    teams.append(r)
teams.sort(key=lambda r: r['rank'])

out = {'snapshot': PROSE['snapshot'], 'lede': PROSE['lede'], 'intro': PROSE['intro'],
       'labels': PROSE['labels'], 'refs': [row(x) for x in REFS], 'teams': teams,
       'closing': PROSE['closing']}
open('data/traditional.js', 'w').write(
    '// Generated by field/scripts/build_traditional.py from field/teams.json +\n'
    '// field/traditional_prose.json. Do not hand-edit; edit the prose file and rebuild.\n'
    'window.SCOUT_TRADITIONAL = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
print('ok', [t['slug'] for t in teams])
